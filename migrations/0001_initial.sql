CREATE TABLE IF NOT EXISTS settings (id INTEGER PRIMARY KEY CHECK(id = 1), value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS posts (id TEXT PRIMARY KEY, created_at TEXT NOT NULL, value TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS posts_created_at ON posts(created_at);
CREATE TABLE IF NOT EXISTS runs (id TEXT PRIMARY KEY, started_at TEXT NOT NULL, value TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS runs_started_at ON runs(started_at);
CREATE TABLE IF NOT EXISTS articles (id TEXT PRIMARY KEY, post_id TEXT NOT NULL, claimed_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS images (post_id TEXT PRIMARY KEY, data BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS locks (name TEXT PRIMARY KEY, owner TEXT NOT NULL, expires_at INTEGER NOT NULL);
